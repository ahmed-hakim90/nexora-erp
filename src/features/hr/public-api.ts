export function employmentProfileRangesOverlap(
  first: Pick<HrEmploymentProfileDefinition, "employeeId" | "effectiveFrom" | "effectiveTo" | "status">,
  second: Pick<HrEmploymentProfileDefinition, "employeeId" | "effectiveFrom" | "effectiveTo" | "status">,
): boolean {
  if (first.employeeId !== second.employeeId || first.status !== "active" || second.status !== "active") {
    return false;
  }

  const firstEnd = first.effectiveTo ?? "9999-12-31";
  const secondEnd = second.effectiveTo ?? "9999-12-31";

  return first.effectiveFrom <= secondEnd && second.effectiveFrom <= firstEnd;
}

export function resolveHrManagerSource(
  input: Readonly<{
    departmentManagerEmployeeId?: string | null;
    positionReportingManagerEmployeeId?: string | null;
    profileReportingManagerEmployeeId?: string | null;
    reportingManagerOverride: boolean;
  }>,
): "employment-profile.override-manager" | "position.reporting-position" | "department.manager" | "unresolved" {
  if (input.reportingManagerOverride && input.profileReportingManagerEmployeeId) {
    return "employment-profile.override-manager";
  }

  if (input.positionReportingManagerEmployeeId) {
    return "position.reporting-position";
  }

  if (input.departmentManagerEmployeeId) {
    return "department.manager";
  }

  return "unresolved";
}

